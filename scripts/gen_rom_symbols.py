#!/usr/bin/env python3
"""Generates src/espressif/rom_symbols.rs from the ROM (and ESP8266 peripheral) linker
scripts.

The mask ROM of each chip is not part of a firmware image, but firmware calls
into it constantly (libc, libgcc, SPI flash and boot helpers). ESP-IDF (for
the ESP32 family) and the ESP8266 RTOS SDK publish the ROM's symbols as linker
scripts.

Peripheral register blocks are left to Espressif's SVD files
(https://github.com/espressif/svd) for the chips that have one, which Binary
Ninja's SVD loader applies with types and register fields. The ESP8266 has
no official SVD, so its peripheral blocks are named from its linker script.

Usage: scripts/gen_rom_symbols.py DIR > src/espressif/rom_symbols.rs
  where DIR/<chip>/*.ld are the files from
  esp-idf components/esp_rom/<chip>/ld/ (except *.api.ld, which are aliases),
  ESP8266_RTOS_SDK components/esp8266/ld/esp8266.{rom,peripherals}.ld and
  ESP8266_NONOS_SDK ld/eagle.rom.addr.v6.ld.

Scripts named <chip>.rom.eco<N>.ld describe functions that only exist in the
ROM of chip revision N and later (the ESP32 ECO3 / v3.0 ROM). They go into a
separate per-revision table so the loader can apply them only to images that
require that revision.
"""
import os
import re
import sys

PAT = re.compile(r"^\s*(?:PROVIDE\s*\(\s*)?([A-Za-z_.$][\w.$]*)\s*=\s*(0x[0-9a-fA-F]+)\s*\)?\s*;", re.M)

root = sys.argv[1]
print("// @generated by scripts/gen_rom_symbols.py; do not edit.")
print("//! ROM function/data symbols (and ESP8266 peripheral register blocks),")
print("//! from the linker scripts of ESP-IDF v5.3 and the ESP8266 RTOS and NONOS")
print("//! SDKs. ESP32-family peripherals come from Espressif's SVD files instead.")
print()
def parse(path):
    text = re.sub(r"/\*.*?\*/", "", open(path).read(), flags=re.S)
    for name, addr in PAT.findall(text):
        addr = int(addr, 16)
        if addr != 0 and not name.startswith("."):
            yield name, addr


def emit(const, syms):
    print(f"pub static {const}: &[(&str, u32)] = &[")
    for name, addr in sorted(syms.items(), key=lambda kv: (kv[1], kv[0])):
        print(f'    ("{name}", {addr:#010x}),')
    print("];")


for chip in ["esp8266", "esp32", "esp32s2", "esp32s3"]:
    base, revisions = {}, {}
    d = os.path.join(root, chip)
    for f in sorted(os.listdir(d)):
        if not f.endswith(".ld") or f.endswith(".api.ld"):
            continue
        if f.endswith(".peripherals.ld") and chip != "esp8266":
            continue
        eco = re.search(r"\.eco(\d+)\.ld$", f)
        syms = revisions.setdefault(int(eco.group(1)), {}) if eco else base
        for name, addr in parse(os.path.join(d, f)):
            syms.setdefault(name, addr)
    const = chip.upper()
    emit(const, base)
    for rev, syms in sorted(revisions.items()):
        emit(f"{const}_ECO{rev}", syms)
    print(f"/// Symbols that only exist in the ROM of a chip revision, by minimum")
    print(f"/// revision (major * 100 + minor, as in the image header).")
    entries = ", ".join(f"({rev * 100}, {const}_ECO{rev})" for rev in sorted(revisions))
    print(f"pub static {const}_REVISIONS: &[(u16, &[(&str, u32)])] = &[{entries}];")
    print(f"// {len(base)} symbols, {sum(map(len, revisions.values()))} revision-specific", file=sys.stderr)
