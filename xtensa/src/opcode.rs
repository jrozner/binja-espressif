//! The [`Opcode`] enumeration.

macro_rules! opcodes {
    ($($variant:ident => $mnemonic:literal,)*) => {
        /// Every operation the decoder can produce.
        ///
        /// Each variant corresponds to exactly one assembler mnemonic, which is
        /// available through [`Opcode::mnemonic`]. Which opcodes can actually be
        /// produced depends on the [`Isa`](crate::Isa) used for decoding.
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
        #[non_exhaustive]
        pub enum Opcode {
            $(
                #[doc = concat!("`", $mnemonic, "`")]
                $variant,
            )*
        }

        impl Opcode {
            /// All opcodes, in mnemonic order.
            pub const ALL: &'static [Opcode] = &[$(Opcode::$variant,)*];

            /// The assembler mnemonic, as printed by GNU objdump.
            ///
            /// Special and user register accesses (`rsr`, `wsr`, `xsr`, `rur`,
            /// `wur`) return the bare mnemonic; the register name is appended
            /// when the full instruction is formatted (e.g. `rsr.sar`).
            #[must_use]
            pub const fn mnemonic(self) -> &'static str {
                match self {
                    $(Opcode::$variant => $mnemonic,)*
                }
            }
        }
    };
}

