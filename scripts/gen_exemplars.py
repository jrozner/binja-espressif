#!/usr/bin/env python3
"""Generates src/exemplars.rs: one sample encoding per mnemonic for each core.

Intrinsic signatures in Binary Ninja are declared per intrinsic, not per
instruction instance. The plugin derives each intrinsic's declared inputs and
outputs by decoding an exemplar encoding of its opcode, so it needs one valid
encoding of every mnemonic. These come from the objdump-verified fixtures of
the xtensa disassembler crate (tests/data/<chip>.tsv).

Usage: scripts/gen_exemplars.py [path/to/xtensa] > src/exemplars.rs
"""
import os
import sys

root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "..", "xtensa")
seen = {}
for chip in ["esp8266", "esp32", "esp32s2", "esp32s3"]:
    with open(os.path.join(root, "tests", "data", f"{chip}.tsv")) as f:
        for line in f:
            raw, _addr, length, text = line.rstrip("\n").split("\t", 3)
            mnemonic = text.split()[0] if text.split() else ""
            # rsr.sar, wur.threadptr, ... share one opcode.
            for prefix in ("rsr.", "wsr.", "xsr.", "rur.", "wur."):
                if mnemonic.startswith(prefix):
                    mnemonic = prefix[:-1]
            key = (chip, mnemonic)
            if mnemonic and key not in seen:
                seen[key] = (int(raw, 16), int(length))

print("// @generated by scripts/gen_exemplars.py; do not edit.")
print("//! One sample encoding of every mnemonic of each supported core, used to")
print("//! derive intrinsic signatures.")
print()
print("/// (instruction word, length in bytes)")
print("pub static EXEMPLARS: &[(u32, u8)] = &[")
words = sorted(set(seen.values()))
for word, length in words:
    print(f"    ({word:#010x}, {length}),")
print("];")
